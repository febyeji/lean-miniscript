#!/usr/bin/env python3
"""Reproduce descriptor material fixtures with pinned Core/BIP340 references.

Only public test secrets 3, 7, 11 and internal key 5 are used. Input files use
the pins checked by the existing Schnorr and Taproot sighash generators.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
import generate_schnorr_fixtures as schnorr
import generate_taproot_sighash_fixtures as sighash


def generate(reference_path, wallet_path, core_path):
    assert hashlib.sha256(reference_path.read_bytes()).hexdigest() == schnorr.REFERENCE_SHA256
    assert hashlib.sha256(wallet_path.read_bytes()).hexdigest() == sighash.WALLET_SHA256
    assert hashlib.sha256(core_path.read_bytes()).hexdigest() == sighash.CORE_SHA256
    ref = schnorr.load("descriptor_material_bip340", reference_path)
    core = sighash.reference_functions(core_path.read_text())
    group = json.loads(wallet_path.read_text())["keyPathSpending"][0]["given"]
    tx = sighash.parse_transaction(group["rawUnsignedTx"])
    original_spent = [sighash.make_output(item["amountSats"], bytes.fromhex(item["scriptPubKey"]))
                      for item in group["utxosSpent"]]
    secrets = [3, 7, 11]
    keys = [ref.pubkey_gen(secret.to_bytes(32, "big")) for secret in secrets]
    internal = ref.pubkey_gen((5).to_bytes(32, "big"))
    push = lambda data: bytes([len(data)]) + data
    checksig = lambda key: push(key) + b"\xac"
    preimages = [bytes([17]) * 32, bytes([34]) * 32]
    hashes = [sighash.sha256(preimage) for preimage in preimages]
    hashlock = lambda digest: b"\x82\x01\x20\x88\xa8" + push(digest) + b"\x87"
    scripts = {
        "branch": b"\x63" + checksig(keys[0]) + b"\x67" + checksig(keys[1]) + b"\x68",
        "multi": checksig(keys[0]) + push(keys[1]) + b"\xba" + push(keys[2]) + b"\xba\x52\x9c",
        "hashBranch": b"\x63" + push(keys[0]) + b"\xad" + hashlock(hashes[0]) +
                      b"\x67" + push(keys[1]) + b"\xad" + hashlock(hashes[1]) + b"\x68",
    }
    values = {f"key{secret}": key for secret, key in zip(secrets, keys)}
    values["internalKey"] = internal
    for index, preimage in enumerate(preimages):
        values[f"preimage{index}"] = preimage
        values[f"hash{index}"] = hashes[index]
    signing_cases = {
        "branch": [(3, 1), (7, 0)],
        "multi": [(3, 0), (7, 0), (11, 1)],
        "hashBranch": [(3, 0), (7, 0)],
    }
    for name, script in scripts.items():
        leaf = sighash.tagged_hash("TapLeaf", b"\xc0" + sighash.ser_string(script))
        tweak = int.from_bytes(sighash.tagged_hash("TapTweak", internal + leaf), "big")
        assert tweak < ref.n
        point = ref.point_add(ref.lift_x(int.from_bytes(internal, "big")), ref.point_mul(ref.G, tweak))
        assert point is not None
        output = b"\x51\x20" + point[0].to_bytes(32, "big")
        spent = list(original_spent)
        spent[0] = sighash.make_output(spent[0].nValue, output)
        values[name + "Script"] = script
        values[name + "Output"] = output
        for secret, mode in signing_cases[name]:
            key = keys[secrets.index(secret)]
            digest = core["TaprootSignatureHash"](tx, spent, mode, 0, scriptpath=True,
                leaf_script=script, codeseparator_pos=0xffffffff)
            signature = ref.schnorr_sign(digest, secret.to_bytes(32, "big"), bytes(32))
            assert ref.schnorr_verify(digest, key, signature)
            values[f"{name}Sig{secret}Mode{mode}"] = signature + (bytes([mode]) if mode else b"")
    text = "import LeanMiniscript.Bitcoin.TaprootSighashExamples\n\n"
    text += "/-! Generated by scripts/generate_descriptor_material_fixtures.py.\n"
    text += "BIP340 reference: 55083d36ddebcd2a039135a2f4ee74917a5803d3.\n"
    text += "Core sighashes: 9be056a8a72b624dae9623b2f7bded92c2a21c91. -/\n\n"
    text += "namespace LeanMiniscript.Extraction.DescriptorMaterialFixtures\n\n" + schnorr.HEX + "\n"
    for name, value in values.items():
        text += f'def {name} : ByteArray := hex "{value.hex()}"\n'
    return text + "\nend LeanMiniscript.Extraction.DescriptorMaterialFixtures\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bip340-reference", type=Path, required=True)
    parser.add_argument("--wallet-vectors", type=Path, required=True)
    parser.add_argument("--core-script", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.bip340_reference, args.wallet_vectors, args.core_script))
