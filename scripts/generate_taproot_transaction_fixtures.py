#!/usr/bin/env python3
"""Regenerate native Taproot key-path fixtures in TaprootTransactionExamples.lean.

Use these pinned public sources (the existing fixture generators use the same
revisions):
https://raw.githubusercontent.com/bitcoin/bips/55083d36ddebcd2a039135a2f4ee74917a5803d3/bip-0341/wallet-test-vectors.json
https://raw.githubusercontent.com/bitcoin/bips/55083d36ddebcd2a039135a2f4ee74917a5803d3/bip-0340/reference.py
https://raw.githubusercontent.com/bitcoin/bitcoin/9be056a8a72b624dae9623b2f7bded92c2a21c91/test/functional/test_framework/script.py

Example:
  python3 scripts/generate_taproot_transaction_fixtures.py \
    --wallet-vectors /tmp/wallet.json --bip340-reference /tmp/reference.py \
    --core-script /tmp/script.py \
    --output LeanMiniscript/Extraction/TaprootTransactionExamples.lean

The seven original witnesses are copied unchanged. Annex variants use only the
public test keys in those vectors, Core's sighash reference, and the BIP340
reference signer. Source checksums and reference signatures are checked before
writing the generated block; the remaining Lean tests are preserved.
"""
import argparse
from pathlib import Path
import sys

sys.dont_write_bytecode = True
import fixture_common


def generate(args):
    base = fixture_common.load_sighash_generator()
    fixture_common.require_sha256(args.wallet_vectors, base.WALLET_SHA256)
    fixture_common.require_sha256(args.core_script, base.CORE_SHA256)
    fixture_common.require_sha256(
        args.bip340_reference, fixture_common.BIP340_REFERENCE_SHA256)
    # Validate Core's adapters against the official messages and component hashes.
    base.generate(args.wallet_vectors, args.core_script)
    group, tx, spent, core = fixture_common.bip341_keypath_group(
        base, args.wallet_vectors, args.core_script)
    ref = fixture_common.load_module('taproot_transaction_bip340', args.bip340_reference)
    cases = group['inputSpending']
    assert len(cases) == 7
    assert {item['given']['hashType'] for item in cases} == {0, 1, 2, 3, 129, 130, 131}
    lines = [
        '-- BEGIN GENERATED VECTORS',
        '-- Generated by scripts/generate_taproot_transaction_fixtures.py.',
        '-- BIP340/BIP341 source: 55083d36ddebcd2a039135a2f4ee74917a5803d3.',
        '-- Core sighash source: 9be056a8a72b624dae9623b2f7bded92c2a21c91.',
        '-- Original wallet witnesses plus reference-signed annex variants (500102).',
        'private def keyPathFixtures : List KeyPathFixture := [',
    ]
    for item in cases:
        index, mode = item['given']['txinIndex'], item['given']['hashType']
        secret = bytes.fromhex(item['intermediary']['tweakedPrivkey'])
        program = spent[index].scriptPubKey
        assert len(program) == 34 and program[:2] == b'\x51\x20'
        output_key = program[2:]
        assert ref.pubkey_gen(secret) == output_key
        suffix = bytes([mode]) if mode else b''
        witness = item['expected']['witness']
        assert len(witness) == 1
        signature = bytes.fromhex(witness[0])
        assert len(signature) == 64 + len(suffix) and signature[64:] == suffix
        digest = core['TaprootSignatureHash'](tx, spent, mode, index)
        assert ref.schnorr_verify(digest, output_key, signature[:64])
        annex_digest = core['TaprootSignatureHash'](
            tx, spent, mode, index, annex=bytes.fromhex('500102'))
        annex_signature = ref.schnorr_sign(annex_digest, secret, bytes(32))
        assert ref.schnorr_verify(annex_digest, output_key, annex_signature)
        assert not ref.schnorr_verify(digest, output_key, annex_signature)
        assert not ref.schnorr_verify(annex_digest, output_key, signature[:64])
        lines += [
            f'  {{ inputIndex := {index}, hashType := {mode}',
            f'    signature := hex "{signature.hex()}"',
            f'    annexSignature := hex "{(annex_signature + suffix).hex()}" }},',
        ]
    lines += [']', '-- END GENERATED VECTORS']
    content = args.output.read_text()
    if not ('-- VECTOR_DATA' in content or
            ('-- BEGIN GENERATED VECTORS' in content and '-- END GENERATED VECTORS' in content)):
        raise SystemExit('Output must contain a generated-vector marker')
    fixture_common.rewrite_generated_block(args.output, '\n'.join(lines))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['wallet-vectors', 'bip340-reference', 'core-script', 'output']:
        parser.add_argument('--' + name, type=Path, required=True)
    generate(parser.parse_args())
